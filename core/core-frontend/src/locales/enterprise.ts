// These management labels are literal text. Message functions avoid runtime code generation under CSP.
type ManagementText = { [key: string]: string | ManagementText }
type ManagementMessages = { [key: string]: (() => string) | ManagementMessages }
const literalMessages = (text: ManagementText): ManagementMessages =>
  Object.fromEntries(
    Object.entries(text).map(([key, value]) => [
      key,
      typeof value === 'string' ? () => value : literalMessages(value)
    ])
  )
export const managementMessages: Record<string, ManagementMessages> = {
  'zh-CN': literalMessages(managementZh),
  en: literalMessages(managementEn),
  tw: literalMessages(managementTw)
}
